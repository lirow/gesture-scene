// ---------------- 场景主题（preset 配置） ----------------
// 粉色爱心的色调：深玫瑰紫的夜空 + 淡粉散光 + 慢速飘落的花瓣尘。
// 具体怎么用由引擎决定，这里只给值。

export const theme = {
  // 背景径向渐变：中心偏上一点玫瑰紫，四周压到近黑。
  // 不要用纯黑 —— 粉色的辉光需要一点底色托着，才不会像贴纸。
  sky: [
    [0, '#4d1233'],
    [0.38, '#320d22'],
    [0.72, '#1a0612'],
    [1, '#070208'],
  ],
  skySize: 512,
  fog: { color: 0x18050f, density: 0.026 },

  exposure: 1.02,
  camera: {
    fov: 45,
    z: 5.7,
    y: 0.10,
    lookAt: [0, 0, 0],
  },

  // 炸开时相机后撤的距离，配合 fit 缩放让星云不撞出屏幕
  expandCamZ: 4.2,

  // 环境飘落粒子：圣诞树是雪，这里是「花瓣尘」——更慢、更大、更淡。
  ambient: {
    color: 0xffc3dd,
    size: 0.115,
    opacity: 0.40,
    spreadX: 16,
    spreadY: 12,
    zFrom: -4,
    zDepth: 6.5,
    speedMin: 0.05,      // 比雪慢得多，才有飘的感觉
    speedRange: 0.16,
  },

  /**
   * 氛围光：一张大范围柔光贴在主体背后，给粉色垫一层「光」。
   * 这不是粒子，而是画面级的雾气 —— 只有粒子在亮时，整体会显得干、没有光感。
   */
  aura: {
    enabled: true,
    color: '#ff3d86',
    expandGrow: 0.55,   // 展开成星云时跟着变大
    expandFade: 0.45,   // 同时淡掉一部分，别糊住星云
    pulse: 0.10,        // 随心跳微微呼吸
    // 两层：内核小而亮（光源），外圈大而淡（空气里的雾）。
    // 只有一层时要么像贴纸、要么像脏镜头。
    layers: [
      { size: 3.4, opacity: 0.42, z: -0.9, y: 0.02 },
      { size: 7.6, opacity: 0.42, z: -2.0, y: 0.02 },
    ],
  },

  /**
   * 竖屏/小屏自适应：主体需要占用的半宽/半高（世界单位），[静止, 完全展开]。
   * 静态度量：心宽 2.60 → 半宽 1.30，高 2.54 → 半高 1.27，各留一点余量。
   */
  fit: {
    halfW: [1.55, 3.90],
    halfH: [1.50, 3.95],
  },
};
